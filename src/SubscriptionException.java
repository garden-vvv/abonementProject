/**
 * Непроверяемое исключение модели абонементов.
 *
 * <p>Используется для недопустимых операций и некорректных аргументов:
 * пустой идентификатор, неположительное число периодов или дней,
 * заморозка, запрещённая для типа абонемента, студенческий абонемент не для студента.</p>
 */
public class SubscriptionException extends RuntimeException {
    /**
     * Создаёт исключение с указанным сообщением.
     *
     * @param message описание ошибки
     */
    public SubscriptionException(String message) {
        super(message);
    }
}
